package com.example;

/**
 * The Colors enum represents the various colors that can be assigned to squares or pawns on the board.
 */
public enum Colors {
    /**
     * White color.
     */
    WHITE,

    /**
     * Red color.
     */
    RED,

    /**
     * Green color.
     */
    GREEN,

    /**
     * Black color.
     */
    BLACK,

    /**
     * Blue color.
     */
    BLUE,

    /**
     * Yellow color.
     */
    YELLOW,

    /**
     * Null color, representing no specific color.
     */
    NULL;
}
